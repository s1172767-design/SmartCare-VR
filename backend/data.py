    """对外输出情景时，剔掉正确答案与解释，避免前端直接看到答案。"""
    return {
        **scenario,
        "steps": [
            {key: value for key, value in step.items() if key not in ("correct", "feedback")}
            for step in scenario["steps"]
        ],
    }
